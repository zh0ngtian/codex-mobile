let activeLocale: Locale = "zh-CN";

export function detectLocale(language: string): Locale {
  return language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function getActiveLocale() {
  return activeLocale;
}

function interpolate(
  value: string,
  variables: Record<string, string | number> = {},
) {
  return value.replace(/\{(\w+)\}/g, (_, key: string) =>
    String(variables[key] ?? `{${key}}`),
  );
}

export function t(
  key: string,
  variables?: Record<string, string | number>,
) {
  const value = activeLocale === "en" ? english[key] ?? key : key;
  return interpolate(value, variables);
}

export function hasEnglishTranslation(key: string) {
  return Object.prototype.hasOwnProperty.call(english, key);
}

interface I18nContextValue {
  locale: Locale;
  preference: LanguagePreference;
  setPreference: (preference: LanguagePreference) => void;
}

const I18nContext = createContext<I18nContextValue | null>(null);

function readPreference(): LanguagePreference {
  const saved = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
  return saved === "zh-CN" || saved === "en" ? saved : "system";
}

export function I18nProvider({
  children,
  navigatorLanguage = window.navigator.language,
}: {
  children: ReactNode;
  navigatorLanguage?: string;
}) {
  const [preference, setPreferenceState] =
    useState<LanguagePreference>(readPreference);
  const locale =
    preference === "system" ? detectLocale(navigatorLanguage) : preference;
  activeLocale = locale;

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      preference,
      setPreference(next) {
        setPreferenceState(next);
        if (next === "system") window.localStorage.removeItem(LANGUAGE_STORAGE_KEY);
        else window.localStorage.setItem(LANGUAGE_STORAGE_KEY, next);
      },
    }),
    [locale, preference],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  return context ?? {
    locale: activeLocale,
    preference: "system" as const,
    setPreference: () => undefined,
  };
}
